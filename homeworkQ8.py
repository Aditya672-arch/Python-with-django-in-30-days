#Membership Operator
'''
Definition: Membership operators are used to check whether an element is present in a sequence (list, tuple, string, etc.).

Python has two membership operators:
1. in
2. not in
'''

a = [10, 20, 30, 40]

print(20 in a)
print(50 in a)
print(50 not in a)
print(10 not in a)